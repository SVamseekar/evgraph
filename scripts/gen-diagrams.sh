#!/usr/bin/env bash
# Regenerate code-derived diagrams into docs/diagrams/generated/.
#
# Every diagram here is produced by a static-analysis tool reading the source
# or workflow files, so re-running this script after a change keeps them in
# sync. Requires: uv (tools run via uvx, nothing is added to the project venv)
# and Graphviz (`brew install graphviz`) for the SVG outputs.
#
# Usage: scripts/gen-diagrams.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/reference/python"
OUT="$ROOT/docs/diagrams/generated"
INDEX="$ROOT/docs/diagrams/README.md"

PACKAGES=(evgraph-core:evgraph_core evgraph-rules:evgraph_rules evgraph:evgraph evgraph-cli:evgraph_cli)

mkdir -p "$OUT"
export PYTHONPATH="$SRC/evgraph-core/src:$SRC/evgraph-rules/src:$SRC/evgraph/src:$SRC/evgraph-cli/src"

echo "==> Class and package diagrams (pyreverse)"
for entry in "${PACKAGES[@]}"; do
  dist="${entry%%:*}"
  mod="${entry##*:}"
  uvx --quiet --from pylint pyreverse --filter-mode PUB_ONLY -o mmd -p "$mod" -d "$OUT" "$SRC/$dist/src/$mod" >/dev/null
done

echo "==> Module dependency graph (pydeps)"
uvx --quiet pydeps --noshow --max-bacon 0 --rankdir LR \
  --only evgraph_core evgraph_rules evgraph evgraph_cli \
  -o "$OUT/module-deps.svg" "$SRC/evgraph-cli/src/evgraph_cli"

echo "==> Call graph (code2flow)"
uvx --quiet code2flow --quiet --hide-legend -o "$OUT/call-graph.svg" \
  "$SRC/evgraph-core/src/evgraph_core" \
  "$SRC/evgraph-rules/src/evgraph_rules" \
  "$SRC/evgraph/src/evgraph" \
  "$SRC/evgraph-cli/src/evgraph_cli"

echo "==> CI/CD pipeline diagrams (workflow YAML)"
uvx --quiet --with pyyaml python "$ROOT/scripts/workflow_to_mermaid.py" \
  "$ROOT"/.github/workflows/*.yml > "$OUT/pipelines.md"

echo "==> Index ($INDEX)"
{
  echo "# Diagrams"
  echo
  echo "Generated by \`scripts/gen-diagrams.sh\` from the source and workflow files."
  echo "Do not edit by hand; re-run the script after code or workflow changes."
  echo
  echo "## Module dependencies"
  echo
  echo "Import graph across all four packages (pydeps). \`evgraph_rules\` does not"
  echo "appear because rules are loaded at run time, not imported."
  echo
  echo "![Module dependencies](generated/module-deps.svg)"
  echo
  echo "## Call graph"
  echo
  echo "Function-level calls (code2flow): [call-graph.svg](generated/call-graph.svg)"
  echo
  echo "## CI/CD pipelines"
  echo
  cat "$OUT/pipelines.md"
  for entry in "${PACKAGES[@]}"; do
    mod="${entry##*:}"
    echo "## \`$mod\`"
    echo
    for kind in packages classes; do
      # pyreverse writes a bare header when a package defines no classes.
      [ "$(wc -l < "$OUT/${kind}_${mod}.mmd")" -gt 1 ] || continue
      if [ "$kind" = packages ]; then echo "### Packages"; else echo "### Classes"; fi
      echo
      echo '```mermaid'
      cat "$OUT/${kind}_${mod}.mmd"
      echo '```'
      echo
    done
  done
} > "$INDEX"

echo "Done. Open $INDEX (Markdown preview) or view it on GitHub."
